async page => {
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const nav = name => page.getByRole('navigation').getByRole('button', {name, exact:true}).click();
  const button = name => page.getByRole('button', {name, exact:true});
  const state = () => page.locator('.metric').filter({hasText:'ROBOT STATE'}).locator('.value').innerText();
  const pose = () => page.getByRole('img', {name:'Editable maze and robot with eight sensors'}).locator('g[transform]').getAttribute('transform');
  await nav('Dashboard');
  assert(await button('Pause').isDisabled(), 'Idle Pause should be disabled');
  await button('Start learning run').click();
  await page.getByText(/Zero motor values keep the robot stationary/).waitFor();
  assert(await state()==='SCAN', 'Blank sketch did not start');
  await button('Reset').click();
  await nav('Day 2 workshop');
  await page.getByLabel('Load student ino').setInputFiles('D:/RAI Mobile Robot/maze-robot-control/maze-robot-control-v3/workshop/student-examples/00_complete/workshop_robot/workshop_robot.ino');
  await page.waitForFunction(() => document.querySelector('[aria-label="Student Arduino exercises"]').value.includes('Complete motor values'));
  await nav('Dashboard');
  const initial = await pose();
  await button('Start learning run').click();
  await page.getByRole('status').filter({hasText:'Simulation started with your loaded Arduino exercises.'}).waitFor();
  await page.waitForTimeout(300);
  assert(await pose()!==initial, 'Complete sketch robot did not move');
  await button('Pause').click();
  assert(await state()==='PAUSED', 'Pause failed');
  const paused=await pose();
  await page.waitForTimeout(200);
  assert(await pose()===paused, 'Paused robot drifted');
  await button('Step').click();
  assert(await pose()!==paused && await state()==='PAUSED', 'Step failed');
  await button('Resume').click();
  await page.getByLabel('Simulation speed').selectOption('4');
  await page.waitForFunction(() => [...document.querySelectorAll('.metric')].find(e=>e.textContent.includes('ROBOT STATE'))?.querySelector('.value')?.textContent==='PATH_READY', {timeout:20000});
  assert(await button('Pause').isDisabled(), 'Finished run can be paused');
  await button('Run optimized path').click();
  await page.waitForFunction(() => [...document.querySelectorAll('.metric')].find(e=>e.textContent.includes('ROBOT STATE'))?.querySelector('.value')?.textContent==='RUN_PATH');
  await page.waitForFunction(() => [...document.querySelectorAll('.metric')].find(e=>e.textContent.includes('ROBOT STATE'))?.querySelector('.value')?.textContent==='PATH_READY', {timeout:10000});
  await nav('Day 2 workshop');
  assert((await page.getByRole('textbox',{name:'Student Arduino exercises'}).inputValue()).includes('Complete motor values'), 'Loaded sketch lost across tabs');
  await button('Run student simulation').click();
  await button('Pause animation').waitFor();
  await button('EMERGENCY STOP').click();
  await button('Play animation').waitFor();
  await nav('Dashboard');
  await nav('Day 2 workshop');
  assert(await button('Play animation').isEnabled(), 'Workshop run lost across tabs');
  await page.screenshot({path:'output/playwright/workshop-after-dashboard-fixes.png',fullPage:true});
  assert(errors.length===0, 'Browser errors: '+errors.join('; '));
  console.log('PASS: blank-sketch feedback, loaded code shared across tabs, dashboard movement, pause, step, resume, learning finish, replay finish, workshop preservation and emergency stop.');
}
